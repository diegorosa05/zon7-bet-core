/** Remove acentos e símbolos para casar nomes vindos dos dados de partidas. */
function chave(nome: string) {
  return nome
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]/g, "");
}

export function escudoDoTime(nome: string): string | undefined {
  const k = chave(nome);
  return escudos[k] ?? escudos[k.replace(/^(sc|sl|fc|ca|ac|cr)/, "")];
}

